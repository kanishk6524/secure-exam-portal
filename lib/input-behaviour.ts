"use client"
// Watches HOW answers are given: real clicks and key presses come from a person; scripts, injected code and some
// remote-control tools create events that look different. Findings are sent as INPUT_ANOMALY incidents for a reviewer.
// Honest limit: an OS-level remote desktop (or a person) produces genuine-looking events and is not detected here.
import { useEffect, useRef } from "react"

export type InputStats = { clicks: number[]; moves: number; keys: number; untrusted: number }
export type InputFinding = { reason: string; detail: string }

/** Pure check over one observation window (also used by tests). */
export function analyseInput(stats: InputStats, answersChanged: number): InputFinding | null {
  if (stats.untrusted > 0) return { reason: "synthetic-events", detail: `${stats.untrusted} click or key events were generated by code, not by a person` }
  if (answersChanged >= 5 && stats.moves === 0 && stats.keys === 0 && stats.clicks.length === 0) return { reason: "answers-without-input", detail: `${answersChanged} answers changed with no mouse or keyboard activity` }
  if (stats.clicks.length >= 8) {
    const gaps = stats.clicks.slice(1).map((time, i) => time - stats.clicks[i])
    const mean = gaps.reduce((a, b) => a + b, 0) / gaps.length
    const cv = Math.sqrt(gaps.reduce((s, g) => s + (g - mean) ** 2, 0) / gaps.length) / (mean || 1)
    if (mean < 5000 && cv < 0.03) return { reason: "metronome-clicks", detail: `${stats.clicks.length} clicks at a nearly identical interval of ${(mean / 1000).toFixed(2)} s` }
  }
  return null
}

export function useInputBehaviour(sessionId: string | undefined, active: boolean, answersChangedRef: { current: number }) {
  const stats = useRef<InputStats>({ clicks: [], moves: 0, keys: 0, untrusted: 0 })
  const lastReport = useRef<Record<string, number>>({})
  useEffect(() => {
    if (!sessionId || !active) return
    const onClick = (event: Event) => { if (!event.isTrusted) stats.current.untrusted += 1; else stats.current.clicks.push(Date.now()) }
    const onKey = (event: Event) => { if (!event.isTrusted) stats.current.untrusted += 1; else stats.current.keys += 1 }
    const onMove = () => { stats.current.moves += 1 }
    document.addEventListener("click", onClick, true)
    document.addEventListener("keydown", onKey, true)
    document.addEventListener("mousemove", onMove, { capture: true, passive: true })
    document.addEventListener("touchstart", onMove, { capture: true, passive: true })
    const timer = window.setInterval(() => {
      const finding = analyseInput(stats.current, answersChangedRef.current)
      stats.current = { clicks: stats.current.clicks.slice(-12), moves: 0, keys: 0, untrusted: 0 }
      answersChangedRef.current = 0
      if (!finding || Date.now() - (lastReport.current[finding.reason] ?? 0) < 120_000) return
      lastReport.current[finding.reason] = Date.now()
      void fetch(`/api/exams/session/${sessionId}/incident`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ type: "INPUT_ANOMALY", severity: "MEDIUM", metadata: finding }) }).catch(() => undefined)
    }, 30_000)
    return () => {
      document.removeEventListener("click", onClick, true)
      document.removeEventListener("keydown", onKey, true)
      document.removeEventListener("mousemove", onMove, true)
      document.removeEventListener("touchstart", onMove, true)
      window.clearInterval(timer)
    }
  }, [sessionId, active, answersChangedRef])
}
